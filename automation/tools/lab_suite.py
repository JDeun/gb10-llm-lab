HOME = Path.home()
LLM = HOME / "llm"
LAB = HOME / "gb10-llm-lab"
TOOLS = LLM / "tools"
sys.path.insert(0, str(TOOLS))
from export_public import redact

PROFILES = {
    "full": {"caps": [1, 16, 64, 256], "sanity": [("sanity", 512), ("sanity", 2048)], "throughput": 3, "conc": True},
    "standard": {"caps": [1, 16, 64, 256], "sanity": [("sanity", 512)], "throughput": 3, "conc": True},
    "slow": {"caps": [1, 16, 64], "sanity": [("sanity", 512)], "throughput": 1, "conc": False},
    "capacity": {"caps": [1, 16, 64], "sanity": [("sanity-mini", 512)], "throughput": 1, "conc": False},
}
CASE_FILES = {"sanity": LAB / "prompts/sanity.jsonl", "sanity-mini": LLM / "prompts/sanity-mini.jsonl"}
THROUGHPUT = LAB / "prompts/throughput_ko.txt"
ENGINE_REVISIONS = {
    "vllm": "vllm/vllm-openai:v0.32.0",
    "strata": "Strata v0.2.13 (engine 0.1.59)",
    "llamacpp": "llama.cpp v0.9.0 (cd959ba), CUDA sm_121 build",
    "ikllama": "ik_llama.cpp main (2a0832d), CUDA sm_121, -march=armv8.6-a+dotprod+i8mm+bf16+fp16",
    "inferssd": "InferSSD 0.1.4 (261109.216.02ed6a8)",
    "colibri": "colibri main (0a5504a), coli build --gpu auto",
}


class EntryFailed(Exception):
    """A queue entry could not finish; kind is a protocol failure label (oom, start_timeout, ...)."""

    def __init__(self, kind: str, detail: str):
        super().__init__(f"{kind}: {detail}")
        self.kind, self.detail = kind, detail


def log(msg: str) -> None:
    print(f"[{datetime.now():%m-%d %H:%M:%S}] {msg}", flush=True)


def server_up(port: int) -> bool:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/v1/models", timeout=15) as resp:
            return resp.status == 200
    except OSError:
        return False


def manifest_path(eid: str) -> Path:
    return LLM / "manifests" / f"{eid}.json"


def write_manifest(entry: dict, alias: str | None) -> Path:
    engine_rev = ENGINE_REVISIONS.get(entry["engine"], entry["engine"])
    command = (entry.get("launch") or entry.get("vllm_args") or entry.get("llama_args")
               or entry.get("inferssd_args") or entry.get("colibri_args") or [])
    spec = {"experiment_id": f"{datetime.now():%Y-%m-%d}-{entry['id']}",
            "model": {"api_alias": alias, "repository": entry["repository"],
                      "quantization": ", ".join(entry.get("hf_include", [])) or None,
                      "pruned": False},
            "engine": {"name": entry["engine"], "revision": engine_rev,
                       "startup_command_without_secrets": " ".join(command)},
            "workload": {"temperature": 0, "thinking_mode": "model/engine default"},
            "notes": ["Generated by the unattended queue runner (~/llm/tools/lab_runner.py)."] + entry.get("notes", [])}
    spec_path = LLM / "manifests" / f"{entry['id']}.spec.json"
    spec_path.write_text(json.dumps(spec, ensure_ascii=False, indent=1), encoding="utf-8")
    out = manifest_path(entry["id"])
    subprocess.run(["python3", str(TOOLS / "make_manifest.py"), "--spec", str(spec_path),
                    "--storage-path", str(HOME), "--out", str(out)], capture_output=True, check=False)
    return out


# ---------- suite ----------

def bench(port: int, alias: str, out: Path, args: list[str], timeout_s: int) -> str:
    cmd = ["python3", str(LAB / "benchmarks/bench.py"), "run", "--base-url", f"http://127.0.0.1:{port}",
           "--model", alias, "--manifest", str(manifest_path(out.parent.name)), "--timeout", "1800",
           "--output-dir", str(out), *args]
    try:
        subprocess.run(cmd, capture_output=True, timeout=timeout_s, check=False)
        return "ok"
    except subprocess.TimeoutExpired:
        return f"step_timeout_{timeout_s}s"


def plan_steps(entry: dict) -> list[tuple[str, list[str]]]:
    prof = PROFILES[entry["profile"]]
    tput_tokens = "64" if entry["profile"] == "capacity" else "256"
    steps = [(f"capacity-cap{c}", ["--prompt-file", str(THROUGHPUT), "--max-tokens", str(c), "--repeats", "1",
                                   "--telemetry", "--case-label", f"capacity-cap{c}"]) for c in prof["caps"]]
    steps += [(f"{name}-{budget}", ["--cases-file", str(CASE_FILES[name]), "--max-tokens", str(budget),
                                    "--repeats", "1", "--case-label", f"{name}-{budget}"]) for name, budget in prof["sanity"]]
    steps += [(f"context-{c}", ["--cases-file", str(LLM / f"prompts/ctx-{c}.jsonl"), "--max-tokens", "1024",
                                "--repeats", "1", "--telemetry", "--case-label", f"context-retrieval-{c}"])
              for c in entry.get("context", [])]
    steps += [(f"throughput-{i}", ["--prompt-file", str(THROUGHPUT), "--max-tokens", tput_tokens, "--repeats", "1",
                                   "--telemetry", "--case-label", f"throughput-{tput_tokens}"])
              for i in range(1, prof["throughput"] + 1)]
    return steps


def run_concurrency(port: int, alias: str, base: Path, timeout_s: int) -> str:
    procs = []
    for c in range(1, 5):
        cmd = ["python3", str(LAB / "benchmarks/bench.py"), "run", "--base-url", f"http://127.0.0.1:{port}",
               "--model", alias, "--manifest", str(manifest_path(base.name)), "--prompt-file", str(THROUGHPUT),
               "--max-tokens", "256", "--repeats", "2", "--case-label", f"concurrency4-client{c}",
               "--output-dir", str(base / f"concurrency4-client{c}")]
        procs.append(subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))
    deadline = time.time() + timeout_s
    for p in procs:
        try:
            p.wait(timeout=max(1, deadline - time.time()))
        except subprocess.TimeoutExpired:
            p.kill()
            return f"step_timeout_{timeout_s}s"
    dirs = [str(base / f"concurrency4-client{c}") for c in range(1, 5)]
    subprocess.run(["python3", str(TOOLS / "concurrency.py"), "--out", str(base / "concurrency4-summary.json"), *dirs],
                   capture_output=True, check=False)
    return "ok"


def run_suite(entry: dict, alias: str, port: int, step_timeout_s: int) -> None:
    base = LAB / "local" / entry["id"]
    if base.exists():
        base.rename(base.with_name(f"{base.name}-partial-{datetime.now():%m%d%H%M}"))
    base.mkdir(parents=True)
    write_manifest(entry, alias)
    outcomes = {}
    try:
        for name, args in plan_steps(entry):
            if not server_up(port):
                outcomes[name] = "server_down_before_step"
                raise EntryFailed("server_down", f"server stopped answering before step {name}")
            log(f"{entry['id']} step {name}")
            outcomes[name] = bench(port, alias, base / name, args, step_timeout_s)
        if PROFILES[entry["profile"]]["conc"] and server_up(port):
            outcomes["concurrency4"] = run_concurrency(port, alias, base, step_timeout_s)
        if entry.get("vision") and server_up(port):
            subprocess.run(["python3", str(TOOLS / "vision_check.py"), "--base-url", f"http://127.0.0.1:{port}",
                            "--model", alias, "--out", str(base / "vision-check.json")],
                           capture_output=True, timeout=step_timeout_s, check=False)
            outcomes["vision-check"] = "ok"
    finally:
        (base / "steps.json").write_text(json.dumps(outcomes, indent=1), encoding="utf-8")


