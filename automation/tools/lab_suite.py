def render_readme(entry: dict, alias: str | None, dst: Path, failure: dict | None, evicted: list[str]) -> str:
    status = f"실패 (`{failure['kind']}`)" if failure else "완료"
    table = (dst / "TABLE.md").read_text(encoding="utf-8") if (dst / "TABLE.md").exists() else "(측정 결과 없음)\n"
    steps = (LAB / "local" / entry["id"] / "steps.json")
    extras = []
    for name in ("concurrency4-summary.json", "vision-check.json"):
        if (dst / name).exists():
            data = json.loads((dst / name).read_text(encoding="utf-8"))
            data.pop("rows", None)
            extras.append(f"- `{name}`: `{json.dumps(data, ensure_ascii=False)}`")
    lines = [f"# {datetime.now():%Y-%m-%d} · {entry['engine']} · {entry['id']} (자동 실행)", "",
             f"**상태:** {status}  ", "**작성:** 무인 실행기(`lab_runner.py`)가 생성했습니다. 해석은 아직 붙이지 않았습니다.", "",
             "| 항목 | 값 |", "|---|---|", f"| 저장소 | {entry['repository']} |",
             f"| 받은 파일 | {', '.join(entry.get('hf_include', [])) or '전체/엔진 기본'} (예상 {entry.get('size_bytes', 0) / 1e9:.0f} GB) |",
             f"| 엔진 옵션 | `{' '.join(entry.get('launch') or entry.get('vllm_args') or entry.get('llama_args') or [])}` |",
             f"| API 별칭 | {alias} |", f"| 측정 프로필 | {entry['profile']} |",
             f"| 공간 확보로 지운 모델 | {', '.join(evicted) or '-'} |", ""]
    if steps.exists():
        lines += [f"단계 결과: `{steps.read_text(encoding='utf-8').strip()}`", ""]
    lines += ["## 결과", "", table] + extras
    if failure:
        lines += ["", "## 실패 정보", "", f"- 종류: `{failure['kind']}`", f"- 내용: {failure['detail']}", "",
                  "엔진 로그 끝부분:", "", "```", failure.get("engine_log_tail", "")[-1500:], "```"]
    lines += ["", "측정이 끝난 모델 파일은 결과 커밋 후 디스크 확보를 위해 삭제합니다."]
    return redact("\n".join(lines) + "\n")


def export_and_commit(entry: dict, alias: str | None, result_dir: Path, failure: dict | None,
                      digest_text: str, evicted: list[str]) -> None:
    eid = entry["id"]
    man = manifest_path(eid) if manifest_path(eid).exists() else write_manifest(entry, alias)
    dig = LLM / "digests" / f"{eid}.sha256"
    dig.write_text(digest_text, encoding="utf-8")
    dst = LLM / "export" / result_dir.name
    shutil.rmtree(dst, ignore_errors=True)
    src = LAB / "local" / eid
    if src.exists():
        subprocess.run(["python3", str(TOOLS / "export_public.py"), "--src", str(src), "--dst", str(dst),
                        "--manifest", str(man), "--digests", str(dig)], capture_output=True, check=False)
    dst.mkdir(parents=True, exist_ok=True)
    if not (dst / "manifest.json").exists():
        (dst / "manifest.json").write_text(redact(man.read_text(encoding="utf-8")), encoding="utf-8")
    shutil.rmtree(result_dir, ignore_errors=True)
    shutil.copytree(dst, result_dir)
    (result_dir / "README.md").write_text(render_readme(entry, alias, dst, failure, evicted), encoding="utf-8")
    status = f"실패({failure['kind']})" if failure else "완료"
    msg = f"[docs] {eid} 자동 실험 결과 ({status})\n\n무인 실행기 생성\n\nCo-Authored-By: Claude <noreply@anthropic.com>"
    subprocess.run(["git", "-C", str(LAB), "add", str(result_dir)], check=False)
    subprocess.run(["git", "-C", str(LAB), "commit", "-q", "-m", msg], check=False)
    log(f"{eid} committed locally ({status})")
